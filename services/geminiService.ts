
import { GoogleGenAI, Modality, Part, GenerateContentResponse, Type } from "@google/genai";
import { ImageFile } from '../types';

if (!process.env.API_KEY) {
  throw new Error("API_KEY environment variable not set");
}

const SAFETY_SETTINGS = [
  { category: 'HARM_CATEGORY_HATE_SPEECH', threshold: 'BLOCK_ONLY_HIGH' },
  { category: 'HARM_CATEGORY_SEXUALLY_EXPLICIT', threshold: 'BLOCK_NONE' },
  { category: 'HARM_CATEGORY_DANGEROUS_CONTENT', threshold: 'BLOCK_ONLY_HIGH' },
  { category: 'HARM_CATEGORY_HARASSMENT', threshold: 'BLOCK_ONLY_HIGH' },
];

export async function generateImage(
  productImage: ImageFile,
  prompt: string,
  styleImage: ImageFile | null
): Promise<ImageFile> {
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });
  const model = 'gemini-2.5-flash-image';

  const parts: Part[] = [
    {
      inlineData: {
        data: productImage.base64,
        mimeType: productImage.mimeType,
      },
    },
    { text: prompt },
  ];

  if (styleImage) {
    parts.push({
      inlineData: {
        data: styleImage.base64,
        mimeType: styleImage.mimeType,
      },
    });
  }

  try {
    const response = await ai.models.generateContent({
      model: model,
      contents: { parts: parts },
      config: {
        responseModalities: [Modality.IMAGE],
        safetySettings: SAFETY_SETTINGS,
      },
    });

    for (const part of response.candidates?.[0]?.content?.parts || []) {
      if (part.inlineData) {
        return {
          base64: part.inlineData.data,
          mimeType: part.inlineData.mimeType,
          name: 'generated-image.jpg',
        };
      }
    }
    
    const safetyText = response.candidates?.[0]?.finishReason;
    if (safetyText) {
        throw new Error(`Image generation failed due to safety settings: ${safetyText}`);
    }

    throw new Error('No image was generated by the model.');

  } catch (error) {
    console.error('Error calling Gemini API:', error);
    if (error instanceof Error) {
        throw error;
    }
    throw new Error('An unexpected error occurred during image generation.');
  }
}

export async function analyzeStyleImage(styleImage: ImageFile): Promise<string> {
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });
  const model = 'gemini-2.5-flash';
  
  const imagePart = {
    inlineData: {
      data: styleImage.base64,
      mimeType: styleImage.mimeType,
    },
  };
  
  const textPart = {
    text: "Analyze this image and describe its aesthetic, color palette, and mood in a concise phrase suitable for a prompt. For example: 'A vibrant, high-contrast style with bold neon colors and a futuristic mood.'",
  };

  try {
    const response: GenerateContentResponse = await ai.models.generateContent({
      model: model,
      contents: { parts: [imagePart, textPart] },
      config: {
        safetySettings: SAFETY_SETTINGS,
      },
    });
    
    if(!response.text) {
      const safetyText = response.candidates?.[0]?.finishReason;
      if (safetyText && safetyText !== 'STOP') {
          throw new Error(`Style analysis failed due to safety settings: ${safetyText}`);
      }
      throw new Error('Model returned no text for style analysis.');
    }
    
    return response.text.trim();

  } catch (error) {
    console.error('Error analyzing style image:', error);
    if (error instanceof Error) {
        throw error;
    }
    throw new Error('An unexpected error occurred during style analysis.');
  }
}

export async function upscaleImage(image: ImageFile): Promise<ImageFile> {
  return new Promise((resolve, reject) => {
    // Simulate network delay and processing
    setTimeout(() => {
      const img = new Image();
      img.src = `data:${image.mimeType};base64,${image.base64}`;
      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          return reject(new Error("Could not get canvas context for upscaling."));
        }

        // Upscale by 2x
        const upscaleFactor = 2;
        canvas.width = img.width * upscaleFactor;
        canvas.height = img.height * upscaleFactor;

        // Draw the image scaled up
        ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

        // Get the new base64 string (JPEG format)
        const base64 = canvas.toDataURL('image/jpeg', 0.92).split(',')[1];
        
        resolve({
          base64,
          mimeType: 'image/jpeg',
          name: `upscaled-${image.name.replace(/\.[^/.]+$/, "")}.jpg`,
        });
      };
      img.onerror = () => {
        reject(new Error("Failed to load image for upscaling."));
      };
    }, 1500); // 1.5 second delay to simulate API call
  });
}
